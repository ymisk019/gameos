void FontRenderer::init() {
    current_language = LANG_ARABIC;
}

void FontRenderer::set_language(Language lang) {
    current_language = lang;
}

Language FontRenderer::get_language() {
    return current_language;
}

void FontRenderer::toggle_language() {
    current_language = (current_language == LANG_ARABIC) ? LANG_ENGLISH : LANG_ARABIC;
}

const char* FontRenderer::tr(const char* ar, const char* en) {
    return (current_language == LANG_ARABIC) ? ar : en;
}

void FontRenderer::draw_char(int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 126) return;
    const uint8_t* glyph = font8x8_basic[c - 32];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if ((bits >> (7 - col)) & 1) {
                if (scale == 1) {
                    VesaDriver::put_pixel(x + col, y + row, color);
                } else {
                    VesaDriver::fill_rect(x + col * scale, y + row * scale, scale, scale, color);
                }
            }
        }
    }
}

void FontRenderer::draw_arabic_char(int x, int y, uint16_t glyph_index, uint32_t color, int scale) {
    if (glyph_index >= 32) return;
    const uint8_t* glyph = arabic_glyphs[glyph_index];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if ((bits >> (7 - col)) & 1) {
                if (scale == 1) {
                    VesaDriver::put_pixel(x + col, y + row, color);
                } else {
                    VesaDriver::fill_rect(x + col * scale, y + row * scale, scale, scale, color);
                }
            }
        }
    }
}

void FontRenderer::draw_string(int x, int y, const char* str, uint32_t color, int scale) {
    if (!str) return;
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            y += 9 * scale;
            cur_x = x;
        } else {
            draw_char(cur_x, y, *str, color, scale);
            cur_x += 8 * scale;
        }
        str++;
    }
}

static int map_utf8_arabic(uint16_t unicode) {
    // Unicode Arabic range U+0621 to U+064A
    switch (unicode) {
        case 0x0621: return 29; // ء
        case 0x0622: // آ
        case 0x0623: // أ
        case 0x0625: // إ
        case 0x0627: return 0;  // ا
        case 0x0628: return 1;  // ب
        case 0x0629: return 28; // ة
        case 0x062A: return 2;  // ت
        case 0x062B: return 3;  // ث
        case 0x062C: return 4;  // ج
        case 0x062D: return 5;  // ح
        case 0x062E: return 6;  // خ
        case 0x062F: return 7;  // د
        case 0x0630: return 8;  // ذ
        case 0x0631: return 9;  // ر
        case 0x0632: return 10; // ز
        case 0x0633: return 11; // س
        case 0x0634: return 12; // ش
        case 0x0635: return 13; // ص
        case 0x0636: return 14; // ض
        case 0x0637: return 15; // ط
        case 0x0638: return 16; // ظ
        case 0x0639: return 17; // ع
        case 0x063A: return 18; // غ
        case 0x0641: return 19; // ف
        case 0x0642: return 20; // ق
        case 0x0643: return 21; // ك
        case 0x0644: return 22; // ل
        case 0x0645: return 23; // م
        case 0x0646: return 24; // ن
        case 0x0647: return 25; // ه
        case 0x0648: return 26; // و
        case 0x0649: return 30; // ى
        case 0x064A: return 27; // ي
        default: return -1;
    }
}

void FontRenderer::draw_string_utf8(int x, int y, const char* utf8_str, uint32_t color, int scale, bool rtl) {
    if (!utf8_str) return;

    // Buffer tokens for RTL reversal if needed
    struct RenderChar {
        bool is_arabic;
        uint16_t code;
    } chars[128];
    int char_count = 0;

    const uint8_t* p = (const uint8_t*)utf8_str;
    while (*p && char_count < 128) {
        if (*p < 0x80) {
            chars[char_count].is_arabic = false;
            chars[char_count].code = *p;
            p++;
            char_count++;
        } else if ((*p & 0xE0) == 0xC0) {
            uint16_t unicode = ((*p & 0x1F) << 6) | (*(p + 1) & 0x3F);
            p += 2;
            int ar_glyph = map_utf8_arabic(unicode);
            if (ar_glyph >= 0) {
                chars[char_count].is_arabic = true;
                chars[char_count].code = (uint16_t)ar_glyph;
            } else {
                chars[char_count].is_arabic = false;
                chars[char_count].code = '?';
            }
            char_count++;
        } else {
            p++;
        }
    }

    int cur_x = x;
    if (rtl) {
        // Render Arabic RTL from right to left
        for (int i = 0; i < char_count; i++) {
            if (chars[i].is_arabic) {
                draw_arabic_char(cur_x, y, chars[i].code, color, scale);
            } else {
                draw_char(cur_x, y, (char)chars[i].code, color, scale);
            }
            cur_x += 8 * scale;
        }
    } else {
        for (int i = 0; i < char_count; i++) {
            if (chars[i].is_arabic) {
                draw_arabic_char(cur_x, y, chars[i].code, color, scale);
            } else {
                draw_char(cur_x, y, (char)chars[i].code, color, scale);
            }
            cur_x += 8 * scale;
        }
    }
}

void FontRenderer::draw_bilingual_text(int x, int y, const char* ar_text, const char* en_text, uint32_t color, int scale) {
    if (current_language == LANG_ARABIC) {
        draw_string_utf8(x, y, ar_text, color, scale, true);
    } else {
        draw_string(x, y, en_text, color, scale);
    }
}

int FontRenderer::get_string_width(const char* str, int scale) {
    if (!str) return 0;
    return kstrlen(str) * 8 * scale;
}

int FontRenderer::get_utf8_width(const char* str, int scale) {
    if (!str) return 0;
    int count = 0;
    const uint8_t* p = (const uint8_t*)str;
    while (*p) {
        if (*p < 0x80) { p++; }
        else if ((*p & 0xE0) == 0xC0) { p += 2; }
        else { p++; }
        count++;
    }
    return count * 8 * scale;
}
